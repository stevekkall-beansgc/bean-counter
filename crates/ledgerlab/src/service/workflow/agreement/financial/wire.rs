/// Mechanical framing from the actual complete core candidate. It conveys no
/// custody/authentication. The service's private preparation must additionally
/// own the completed chronological prefix and actual current locked snapshot.
#[allow(clippy::too_many_arguments)]
pub(super) fn frame_candidate<'a>(
    candidate: &'a EconomicCandidate,
    key: &OperationKey,
    kind: &'a str,
    evidence: &'a Value,
    received_at: &Timestamp,
    accepted_at: &Timestamp,
    sequence: i64,
    session: &mut OriginalAuditSession,
) -> Result<JournalData<'a>> {
    let result = frame_inner(
        candidate,
        key,
        kind,
        evidence,
        received_at,
        accepted_at,
        sequence,
        session,
    );
    if result.is_err() {
        session.invalidate();
    }
    result
}
#[allow(clippy::too_many_arguments)]
fn frame_inner<'a>(
    candidate: &'a EconomicCandidate,
    key: &OperationKey,
    kind: &'a str,
    evidence: &'a Value,
    received_at: &Timestamp,
    accepted_at: &Timestamp,
    sequence: i64,
    session: &mut OriginalAuditSession,
) -> Result<JournalData<'a>> {
    use super::request_wrapper as request;
    let normalized = request::field(evidence, "normalized_request", session)?;
    request::key(request::field(normalized, "key", session)?, key, session)?;
    for (a, b) in [
        (&candidate.key().logical_store_id, &key.logical_store_id),
        (&candidate.key().scope[0], &key.scope[0]),
        (&candidate.key().scope[1], &key.scope[1]),
        (&candidate.key().source, &key.source),
        (&candidate.key().operation_id, &key.operation_id),
    ] {
        request::same_text(a, b, session)?;
    }
    request::same_text(request::text(normalized, "kind", session)?, kind, session)?;
    let payload = request::field(normalized, "payload", session)?;
    let canonical = session
        .canonical_representation(payload, RepresentationKind::Record)
        .map_err(core_error)?;
    session
        .semantic_work()
        .visit(Visit::MemberCompare)
        .map_err(core_error)?;
    session
        .semantic_work()
        .scan_bytes(canonical.bytes().len())
        .map_err(core_error)?;
    session
        .semantic_work()
        .scan_bytes(candidate.normalized_payload().len())
        .map_err(core_error)?;
    require(
        canonical.bytes() == candidate.normalized_payload(),
        "INTEGRITY_FAILURE",
    )?;
    drop(canonical);
    let resolution = request::field(evidence, "descriptor_resolution", session)?;
    let recipe = wrappers::recipe(
        kind,
        request::text(payload, "schema", session)?,
        request::text(resolution, "registry_digest", session)?,
        session,
    )?;
    let metadata = candidate.result_metadata();
    let mut authority = None;
    for record in candidate.introduced() {
        session
            .semantic_work()
            .visit(Visit::Element)
            .map_err(core_error)?;
        if ref_compare(record.reference(), metadata.authority_ref(), session)?.is_eq() {
            require(authority.is_none(), "INTEGRITY_FAILURE")?;
            authority = Some(record);
        }
    }
    let authority = authority.ok_or(ServiceError::IntegrityFailure)?;
    request::same_text(authority.schema(), recipe.authority, session)?;
    let key_value = request::field(normalized, "key", session)?;
    let scope_value = request::field(key_value, "scope", session)?;
    let key_bytes = session
        .canonical_representation(key_value, RepresentationKind::Record)
        .map_err(core_error)?;
    let scope_bytes = session
        .canonical_representation(scope_value, RepresentationKind::Record)
        .map_err(core_error)?;
    let evidence_bytes = session
        .canonical_representation(evidence, RepresentationKind::Record)
        .map_err(core_error)?;
    let results = RefSet::new(
        metadata.result_refs().iter(),
        metadata.result_refs().len(),
        true,
        session,
    )?;
    require(!results.refs.is_empty(), "INTEGRITY_FAILURE")?;
    let results_bytes = results.encode(session)?;
    let audit=metadata.experimental_audit().ok_or_else(||reject("UNSUPPORTED_SCHEMA_PROFILE"))?;
    let observations = RefSet::new(
        audit.source_observation_refs(),
        audit.source_observation_refs().len(),
        true,
        session,
    )?;
    require(
        !observations.refs.is_empty() && !compare(observations.refs.len(), 32, session)?.is_gt(),
        "INTEGRITY_FAILURE",
    )?;
    let observations_bytes = observations.encode(session)?;
    let financial = reference(audit.financial_observation_ref(), session)?;
    let combined = literal(audit.combined_audit_digest(), session)?;
    let kind_value = literal(kind, session)?;
    let received = literal(received_at.as_str(), session)?;
    let at = literal(accepted_at.as_str(), session)?;
    let sequence_number = sequence;
    let sequence = sequence_string(sequence, session)?;
    let closure = literal(recipe.closure, session)?;
    let operation_schema = literal(recipe.operation, session)?;
    let operation = object(
        &[
            ("accepted_at", at.bytes()),
            ("authority_snapshot", authority.canonical_body()),
            ("closure_profile", closure.bytes()),
            ("combined_audit_digest", combined.bytes()),
            ("commit_sequence", sequence.bytes()),
            ("contract", b"\"workflow/1\""),
            ("financial_observation_ref", financial.bytes()),
            ("key", key_bytes.bytes()),
            ("kind", kind_value.bytes()),
            ("received_at", received.bytes()),
            ("request_evidence", evidence_bytes.bytes()),
            ("result_refs", results_bytes.bytes()),
            ("schema", operation_schema.bytes()),
            ("source_observation_refs", observations_bytes.bytes()),
        ],
        8388608,
        session,
    )?;
    let id_hash = hash(
        b"bean-counter/workflow-operation/1\0",
        &[key_bytes.bytes()],
        session,
    )?;
    let op_hash = hash(
        b"bean-counter/workflow-record/1\0",
        &[
            b"[\"workflow-operation\",",
            scope_bytes.bytes(),
            b",",
            operation.bytes(),
            b"]",
        ],
        session,
    )?;
    let operation_ref = owned_reference("workflow-operation", "wop_", &id_hash, &op_hash, session)?;
    let references = candidate
        .introduced()
        .iter()
        .map(|d| d.reference())
        .chain(candidate.consumed_refs().iter());
    // Chain's exact length is known from these two bounded owned vectors.
    let refs_count = arithmetic(
        candidate.introduced().len(),
        candidate.consumed_refs().len(),
        Op::Add,
        session,
    )?;
    let members = RefSet::new(references, refs_count, false, session)?;
    let count = arithmetic(members.refs.len(), 1, Op::Add, session)?;
    let full = RefSet::new(
        members
            .refs
            .iter()
            .copied()
            .chain(std::iter::once(&operation_ref.reference)),
        count,
        true,
        session,
    )?;
    let member_bytes = full.encode(session)?;
    drop(full);
    let manifest_schema = literal(recipe.manifest, session)?;
    let manifest = object(
        &[
            ("closure_profile", closure.bytes()),
            ("combined_audit_digest", combined.bytes()),
            ("financial_observation_ref", financial.bytes()),
            ("key", key_bytes.bytes()),
            ("members", member_bytes.bytes()),
            ("schema", manifest_schema.bytes()),
            ("source_observation_refs", observations_bytes.bytes()),
        ],
        4194304,
        session,
    )?;
    let manifest_hash = hash(
        b"bean-counter/workflow-manifest/1\0",
        &[manifest.bytes()],
        session,
    )?;
    let manifest_ref = owned_reference(
        "workflow-manifest",
        "wmanifest_",
        &manifest_hash,
        &manifest_hash,
        session,
    )?;
    let result_kind = literal(metadata.result_kind(), session)?;
    let (receipt, receipt_ref) = receipt(
        key_bytes.bytes(),
        at.bytes(),
        sequence.bytes(),
        &manifest_ref,
        result_kind.bytes(),
        results_bytes.bytes(),
        evidence,
        session,
    )?;
    // Store operands borrow the SAME candidate, never reparsed output or a
    // caller-supplied document set. Reserve the pointer/metadata vector before
    // allocation and charge each actual association copy before push.
    let count = candidate.introduced().len();
    require(!compare(count, 4095, session)?.is_gt(), "INTEGRITY_FAILURE")?;
    let document_bytes = arithmetic(
        count,
        std::mem::size_of::<FinancialDocument<'_>>(),
        Op::Multiply,
        session,
    )?;
    let document_bytes = arithmetic(
        document_bytes,
        std::mem::size_of::<Vec<FinancialDocument<'_>>>(),
        Op::Add,
        session,
    )?;
    let documents_lease = session
        .reserve_external_payload(document_bytes)
        .map_err(core_error)?;
    let mut documents = Vec::new();
    documents
        .try_reserve_exact(count)
        .map_err(|_| ServiceError::Unavailable)?;
    for record in candidate.introduced() {
        session
            .semantic_work()
            .visit(Visit::Element)
            .map_err(core_error)?;
        session
            .semantic_work()
            .write_bytes(std::mem::size_of::<FinancialDocument<'_>>())
            .map_err(core_error)?;
        documents.push(FinancialDocument {
            reference: record.reference(),
            schema: record.schema(),
            canonical_bytes: record.canonical_body(),
        });
    }
    Ok(JournalData {
        candidate,
        identity: key_bytes,
        kind,
        request_hash: request::text(evidence, "request_hash", session)?,
        sequence: sequence_number,
        accepted_at_us: accepted_at.micros(),
        documents,
        _documents_lease: documents_lease,
        operation,
        manifest,
        receipt,
        operation_ref,
        manifest_ref,
        receipt_ref,
        members,
    })
}

fn sequence_string(sequence: i64, session: &mut OriginalAuditSession) -> Result<AuditedBytes> {
    session
        .semantic_work()
        .arithmetic(Op::Compare, &[&sequence.into(), &1i64.into()])
        .map_err(core_error)?;
    require(sequence >= 1, "INTEGRITY_FAILURE")?;
    // Canonical decimal formatting is fixed-width stack work, not an unleased
    // dynamic formatter. The accepted profile sequence is at most100,000.
    session
        .semantic_work()
        .arithmetic(Op::Compare, &[&sequence.into(), &100000i64.into()])
        .map_err(core_error)?;
    require(sequence <= 100000, "INTEGRITY_FAILURE")?;
    let mut digits = [0u8; 6];
    let mut value = sequence as u64;
    let mut start = 6;
    loop {
        session
            .semantic_work()
            .arithmetic(Op::DivideRemainder, &[&value.into(), &10u64.into()])
            .map_err(core_error)?;
        let digit = value % 10;
        session
            .semantic_work()
            .arithmetic(Op::Subtract, &[&start.into(), &1usize.into()])
            .map_err(core_error)?;
        start -= 1;
        session
            .semantic_work()
            .arithmetic(Op::Add, &[&digit.into(), &b'0'.into()])
            .map_err(core_error)?;
        session.semantic_work().write_bytes(1).map_err(core_error)?;
        digits[start] = b'0' + digit as u8;
        session
            .semantic_work()
            .arithmetic(Op::DivideRemainder, &[&value.into(), &10u64.into()])
            .map_err(core_error)?;
        value /= 10;
        session
            .semantic_work()
            .arithmetic(Op::Compare, &[&value.into(), &0u64.into()])
            .map_err(core_error)?;
        if value == 0 {
            break;
        }
    }
    literal(
        std::str::from_utf8(&digits[start..]).map_err(|_| ServiceError::IntegrityFailure)?,
        session,
    )
}

// SAME receipt2 recipe shared by economic and administrative framing.
fn receipt(
    key_bytes: &[u8],
    at: &[u8],
    sequence: &[u8],
    manifest_ref: &WireRef,
    result_kind: &[u8],
    results: &[u8],
    evidence: &Value,
    session: &mut OriginalAuditSession,
) -> Result<(AuditedBytes, WireRef)> {
    let resolution = super::request_wrapper::field(evidence, "descriptor_resolution", session)?;
    let manifest_digest = literal(&manifest_ref.reference.digest, session)?;
    let mut receipt_fields = [
        ("accepted_at", at),
        ("commit_sequence", sequence),
        ("descriptor_closure_digest", b"".as_slice()),
        ("key", key_bytes),
        ("manifest_hash", manifest_digest.bytes()),
        (
            "normalization_profile",
            b"\"ledger-operation-normalization/2\"",
        ),
        ("original_request_bytes_sha256", b""),
        ("request_hash", b""),
        (
            "request_hash_profile",
            b"\"bean-counter/operation-request/2\"",
        ),
        ("result_kind", result_kind),
        ("result_refs", results),
        ("schema", b"\"ledger-operation-receipt/2\""),
        ("schema_bundle_digest", b""),
    ];
    let descriptor_digest = literal(
        super::request_wrapper::text(resolution, "closure_digest", session)?,
        session,
    )?;
    let raw_digest = literal(
        super::request_wrapper::text(evidence, "original_request_bytes_sha256", session)?,
        session,
    )?;
    let request_hash_text = super::request_wrapper::text(evidence, "request_hash", session)?;
    let request_hash = literal(request_hash_text, session)?;
    let bundle = literal(
        super::request_wrapper::text(evidence, "schema_bundle_digest", session)?,
        session,
    )?;
    receipt_fields[2].1 = descriptor_digest.bytes();
    receipt_fields[6].1 = raw_digest.bytes();
    receipt_fields[7].1 = request_hash.bytes();
    receipt_fields[12].1 = bundle.bytes();
    let unhashed = object(&receipt_fields, 1048576, session)?;
    let receipt_hash = hash(
        b"bean-counter/operation-receipt/2\0",
        &[unhashed.bytes()],
        session,
    )?;
    drop(unhashed);
    let receipt_ref = owned_reference(
        "workflow-receipt",
        "wreceipt_",
        &receipt_hash,
        &receipt_hash,
        session,
    )?;
    let receipt_digest = literal(&receipt_ref.reference.digest, session)?;
    let receipt = object(
        &[
            ("accepted_at", at),
            ("commit_sequence", sequence),
            ("descriptor_closure_digest", descriptor_digest.bytes()),
            ("key", key_bytes),
            ("manifest_hash", manifest_digest.bytes()),
            (
                "normalization_profile",
                b"\"ledger-operation-normalization/2\"",
            ),
            ("original_request_bytes_sha256", raw_digest.bytes()),
            ("receipt_hash", receipt_digest.bytes()),
            ("request_hash", request_hash.bytes()),
            (
                "request_hash_profile",
                b"\"bean-counter/operation-request/2\"",
            ),
            ("result_kind", result_kind),
            ("result_refs", results),
            ("schema", b"\"ledger-operation-receipt/2\""),
            ("schema_bundle_digest", bundle.bytes()),
        ],
        1048576,
        session,
    )?;
    Ok((receipt, receipt_ref))
}

