fn arithmetic(
    left: usize,
    right: usize,
    op: Op,
    session: &mut OriginalAuditSession,
) -> Result<usize> {
    session
        .semantic_work()
        .arithmetic(op, &[&left.into(), &right.into()])
        .map_err(core_error)?;
    match op {
        Op::Add => left.checked_add(right),
        Op::Multiply => left.checked_mul(right),
        Op::Subtract => left.checked_sub(right),
        _ => None,
    }
    .ok_or(ServiceError::IntegrityFailure)
}
fn compare(left: usize, right: usize, session: &mut OriginalAuditSession) -> Result<Cmp> {
    session
        .semantic_work()
        .arithmetic(Op::Compare, &[&left.into(), &right.into()])
        .map_err(core_error)?;
    Ok(left.cmp(&right))
}
fn append(
    out: &mut AuditedByteBuilder,
    raw: &[u8],
    session: &mut OriginalAuditSession,
) -> Result<()> {
    out.append(raw, session.semantic_work()).map_err(core_error)
}
fn buffer(maximum: usize, session: &mut OriginalAuditSession) -> Result<AuditedByteBuilder> {
    let (arena, work) = session.parts();
    arena.byte_builder(maximum, work).map_err(core_error)
}
// This emitter is deliberately only for the unescaped ASCII literals/Refs
// generated by the closed recipes. Business strings/keys use the SAME core
// canonical Value emitter below; no second general JSON encoder is installed.
fn literal(text: &str, session: &mut OriginalAuditSession) -> Result<AuditedBytes> {
    session
        .semantic_work()
        .visit(Visit::Constraint)
        .map_err(core_error)?;
    session
        .semantic_work()
        .scan_bytes(text.len())
        .map_err(core_error)?;
    require(
        text.bytes()
            .all(|b| (0x20..=0x7e).contains(&b) && b != b'"' && b != b'\\'),
        "INTEGRITY_FAILURE",
    )?;
    let maximum = arithmetic(text.len(), 2, Op::Add, session)?;
    let mut out = buffer(maximum, session)?;
    append(&mut out, b"\"", session)?;
    append(&mut out, text.as_bytes(), session)?;
    append(&mut out, b"\"", session)?;
    out.finish(session.semantic_work()).map_err(core_error)
}
pub(super) fn reference(r: &ExactRef, session: &mut OriginalAuditSession) -> Result<AuditedBytes> {
    reference_parts(&r.kind, &r.id, &r.digest, session)
}
pub(super) fn definition_reference(
    r: &ledgerlab_core::policy::workflow::DefinitionRef,
    session: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    reference_parts(r.kind(), r.id(), r.digest(), session)
}
fn reference_parts(
    kind: &str,
    id: &str,
    digest: &str,
    session: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    let digest = literal(digest, session)?;
    let id = literal(id, session)?;
    let kind = literal(kind, session)?;
    object(
        &[
            ("digest", digest.bytes()),
            ("id", id.bytes()),
            ("kind", kind.bytes()),
        ],
        4194304,
        session,
    )
}
fn ref_compare(
    left: &ExactRef,
    right: &ExactRef,
    session: &mut OriginalAuditSession,
) -> Result<Cmp> {
    session
        .semantic_work()
        .visit(Visit::MemberCompare)
        .map_err(core_error)?;
    // JCS Ref dictionary order is digest,id,kind. These recipe-generated
    // strings are unescaped ASCII; reserve full byte passes before each compare.
    for (a, b) in [
        (&left.digest, &right.digest),
        (&left.id, &right.id),
        (&left.kind, &right.kind),
    ] {
        session
            .semantic_work()
            .scan_bytes(a.len())
            .map_err(core_error)?;
        session
            .semantic_work()
            .scan_bytes(b.len())
            .map_err(core_error)?;
        match a.cmp(b) {
            Cmp::Equal => {}
            ordering => return Ok(ordering),
        }
    }
    Ok(Cmp::Equal)
}
pub(super) struct RefSet<'a> {
    refs: Vec<&'a ExactRef>,
    _lease: ExternalBufferLease,
}
impl<'a> RefSet<'a> {
    /// Strictly checked sorted input; avoids sorting the already ordered
    /// closure index again. This is only a set view, never an origin proof.
    pub(super) fn from_sorted(
        input: impl Iterator<Item = &'a ExactRef>,
        count: usize,
        session: &mut OriginalAuditSession,
    ) -> Result<Self> {
        require(!compare(count, 4096, session)?.is_gt(), "REFERENCE_LIMIT")?;
        let payload = arithmetic(
            count,
            std::mem::size_of::<&ExactRef>(),
            Op::Multiply,
            session,
        )?;
        let lease = session
            .reserve_external_payload(payload)
            .map_err(core_error)?;
        let mut refs: Vec<&ExactRef> = Vec::new();
        refs.try_reserve_exact(count)
            .map_err(|_| ServiceError::Unavailable)?;
        for reference in input {
            session
                .semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            require(
                compare(refs.len(), count, session)?.is_lt(),
                "INTEGRITY_FAILURE",
            )?;
            if let Some(prior) = refs.last() {
                require(
                    ref_compare(prior, reference, session)?.is_lt(),
                    "INTEGRITY_FAILURE",
                )?;
            }
            session
                .semantic_work()
                .write_bytes(std::mem::size_of::<&ExactRef>())
                .map_err(core_error)?;
            refs.push(reference);
        }
        require(
            compare(refs.len(), count, session)?.is_eq(),
            "INTEGRITY_FAILURE",
        )?;
        Ok(Self {
            refs,
            _lease: lease,
        })
    }

    pub(super) fn new(
        input: impl Iterator<Item = &'a ExactRef>,
        count: usize,
        unique: bool,
        session: &mut OriginalAuditSession,
    ) -> Result<Self> {
        let bytes = arithmetic(
            count,
            std::mem::size_of::<&ExactRef>(),
            Op::Multiply,
            session,
        )?;
        let bytes = arithmetic(
            bytes,
            std::mem::size_of::<Vec<&ExactRef>>(),
            Op::Add,
            session,
        )?;
        let lease = session
            .reserve_external_payload(bytes)
            .map_err(core_error)?;
        let mut refs = Vec::new();
        refs.try_reserve_exact(count)
            .map_err(|_| ServiceError::Unavailable)?;
        for reference in input {
            require(
                compare(refs.len(), count, session)?.is_lt(),
                "INTEGRITY_FAILURE",
            )?;
            session
                .semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            session
                .semantic_work()
                .write_bytes(std::mem::size_of::<&ExactRef>())
                .map_err(core_error)?;
            refs.push(reference);
        }
        require(
            compare(refs.len(), count, session)?.is_eq(),
            "INTEGRITY_FAILURE",
        )?;
        let mut out = Self {
            refs,
            _lease: lease,
        };
        out.sort(session)?;
        let mut retained = 0;
        for index in 0..out.refs.len() {
            session
                .semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            let duplicate = if compare(retained, 0, session)?.is_gt() {
                let prior = arithmetic(retained, 1, Op::Subtract, session)?;
                ref_compare(out.refs[prior], out.refs[index], session)?.is_eq()
            } else {
                false
            };
            if duplicate {
                require(!unique, "INTEGRITY_FAILURE")?;
            } else {
                session
                    .semantic_work()
                    .visit(Visit::SortMove)
                    .map_err(core_error)?;
                session
                    .semantic_work()
                    .write_bytes(std::mem::size_of::<&ExactRef>())
                    .map_err(core_error)?;
                out.refs[retained] = out.refs[index];
                retained = arithmetic(retained, 1, Op::Add, session)?;
            }
        }
        out.refs.truncate(retained);
        require(
            !compare(retained, 4096, session)?.is_gt(),
            "INTEGRITY_FAILURE",
        )?;
        Ok(out)
    }
    fn sort(&mut self, session: &mut OriginalAuditSession) -> Result<()> {
        sort_values(&mut self.refs, session, &mut |a, b, s| ref_compare(a, b, s))
    }
    pub(super) fn encode(&self, session: &mut OriginalAuditSession) -> Result<AuditedBytes> {
        let mut maximum = 2;
        for r in &self.refs {
            // Exact unescaped Ref body plus comma; each encoded reference is
            // emitted/released one at a time, not retained as a second graph.
            for bytes in [r.digest.len(), r.id.len(), r.kind.len(), 32] {
                maximum = arithmetic(maximum, bytes, Op::Add, session)?;
            }
        }
        let mut out = buffer(maximum, session)?;
        append(&mut out, b"[", session)?;
        for (index, r) in self.refs.iter().enumerate() {
            session
                .semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            if index != 0 {
                append(&mut out, b",", session)?;
            }
            let encoded = reference(r, session)?;
            append(&mut out, encoded.bytes(), session)?;
        }
        append(&mut out, b"]", session)?;
        out.finish(session.semantic_work()).map_err(core_error)
    }
}
fn swap_values<T>(
    values: &mut [T],
    left: usize,
    right: usize,
    s: &mut OriginalAuditSession,
) -> Result<()> {
    s.semantic_work()
        .visit(Visit::SortMove)
        .map_err(core_error)?;
    s.semantic_work()
        .write_bytes(2 * std::mem::size_of::<T>())
        .map_err(core_error)?;
    values.swap(left, right);
    Ok(())
}
fn sift_values<T>(
    values: &mut [T],
    mut root: usize,
    end: usize,
    s: &mut OriginalAuditSession,
    order: &mut impl FnMut(&T, &T, &mut OriginalAuditSession) -> Result<Cmp>,
) -> Result<()> {
    loop {
        let left = arithmetic(arithmetic(root, 2, Op::Multiply, s)?, 1, Op::Add, s)?;
        if !compare(left, end, s)?.is_lt() {
            return Ok(());
        }
        let right = arithmetic(left, 1, Op::Add, s)?;
        let child = if compare(right, end, s)?.is_lt()
            && order(&values[left], &values[right], s)?.is_lt()
        {
            right
        } else {
            left
        };
        if !order(&values[root], &values[child], s)?.is_lt() {
            return Ok(());
        }
        swap_values(values, root, child, s)?;
        root = child;
    }
}
fn sort_values<T>(
    values: &mut [T],
    s: &mut OriginalAuditSession,
    order: &mut impl FnMut(&T, &T, &mut OriginalAuditSession) -> Result<Cmp>,
) -> Result<()> {
    s.semantic_work()
        .arithmetic(Op::DivideRemainder, &[&values.len().into(), &2usize.into()])
        .map_err(core_error)?;
    for root in (0..values.len() / 2).rev() {
        sift_values(values, root, values.len(), s, order)?;
    }
    for end in (1..values.len()).rev() {
        swap_values(values, 0, end, s)?;
        sift_values(values, 0, end, s, order)?;
    }
    Ok(())
}
fn encoded_order(a: &AuditedBytes, b: &AuditedBytes, s: &mut OriginalAuditSession) -> Result<Cmp> {
    s.semantic_work()
        .visit(Visit::MemberCompare)
        .map_err(core_error)?;
    s.semantic_work()
        .scan_bytes(a.bytes().len())
        .map_err(core_error)?;
    s.semantic_work()
        .scan_bytes(b.bytes().len())
        .map_err(core_error)?;
    Ok(a.bytes().cmp(b.bytes()))
}
/// Sort already owning canonical rows through the SAME wrapper heap kernel,
/// then emit their strict canonical set. This is not raw-document normalization.
pub(super) fn encoded_set(
    rows: &mut [AuditedBytes],
    s: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    let result = (|| {
        sort_values(rows, s, &mut encoded_order)?;
        for pair in rows.windows(2) {
            s.semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            require(encoded_order(&pair[0], &pair[1], s)?.is_lt(), "DUPLICATE")?;
        }
        let mut maximum = 2usize;
        for row in rows.iter() {
            s.semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            maximum = arithmetic(maximum, row.bytes().len(), Op::Add, s)?;
            maximum = arithmetic(maximum, 1, Op::Add, s)?;
        }
        require(!compare(maximum, 4194304, s)?.is_gt(), "RECORD_TOO_LARGE")?;
        let mut out = buffer(maximum, s)?;
        append(&mut out, b"[", s)?;
        for (index, row) in rows.iter().enumerate() {
            s.semantic_work()
                .visit(Visit::Element)
                .map_err(core_error)?;
            if index != 0 {
                append(&mut out, b",", s)?;
            }
            append(&mut out, row.bytes(), s)?;
        }
        append(&mut out, b"]", s)?;
        out.finish(s.semantic_work()).map_err(core_error)
    })();
    if result.is_err() {
        s.invalidate();
    }
    result
}

pub(super) fn object(
    fields: &[(&'static str, &[u8])],
    maximum: usize,
    session: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    let mut length = 2;
    let mut previous: Option<&'static str> = None;
    session
        .semantic_work()
        .visit(Visit::Value)
        .map_err(core_error)?;
    for (index, (name, value)) in fields.iter().enumerate() {
        session
            .semantic_work()
            .visit(Visit::Field)
            .map_err(core_error)?;
        if let Some(old) = previous {
            session
                .semantic_work()
                .visit(Visit::MemberCompare)
                .map_err(core_error)?;
            session
                .semantic_work()
                .scan_bytes(old.len())
                .map_err(core_error)?;
            session
                .semantic_work()
                .scan_bytes(name.len())
                .map_err(core_error)?;
            require(old < *name, "INTEGRITY_FAILURE")?;
        }
        previous = Some(*name);
        length = arithmetic(length, name.len(), Op::Add, session)?;
        length = arithmetic(length, value.len(), Op::Add, session)?;
        length = arithmetic(length, 3, Op::Add, session)?;
        session.semantic_work().arithmetic(Op::Compare,&[&index.into(),&0usize.into()]).map_err(core_error)?;
        if index != 0 {
            length = arithmetic(length, 1, Op::Add, session)?;
        }
    }
    require(
        !compare(length, maximum, session)?.is_gt(),
        "INTEGRITY_FAILURE",
    )?;
    let mut out = buffer(length, session)?;
    append(&mut out, b"{", session)?;
    for (index, (name, value)) in fields.iter().enumerate() {
        session.semantic_work().arithmetic(Op::Compare,&[&index.into(),&0usize.into()]).map_err(core_error)?;
        if index != 0 {
            append(&mut out, b",", session)?;
        }
        append(&mut out, b"\"", session)?;
        append(&mut out, name.as_bytes(), session)?;
        append(&mut out, b"\":", session)?;
        append(&mut out, value, session)?;
    }
    append(&mut out, b"}", session)?;
    out.finish(session.semantic_work()).map_err(core_error)
}
fn hash(domain: &[u8], parts: &[&[u8]], session: &mut OriginalAuditSession) -> Result<[u8; 32]> {
    let mut hash = Sha256::new();
    for bytes in std::iter::once(&domain).chain(parts) {
        session
            .semantic_work()
            .scan_bytes(bytes.len())
            .map_err(core_error)?;
        session
            .semantic_work()
            .hash_bytes(bytes.len())
            .map_err(core_error)?;
        hash.update(bytes);
    }
    session
        .semantic_work()
        .write_bytes(32)
        .map_err(core_error)?;
    Ok(hash.finalize().into())
}
fn digest(raw: &[u8; 32]) -> [u8; 71] {
    let mut out = [0; 71];
    out[..7].copy_from_slice(b"sha256:");
    const HEX: &[u8; 16] = b"0123456789abcdef";
    for (byte, pair) in raw.iter().zip(out[7..].chunks_exact_mut(2)) {
        pair[0] = HEX[(byte >> 4) as usize];
        pair[1] = HEX[(byte & 15) as usize];
    }
    out
}
struct WireRef {
    reference: ExactRef,
    _lease: ExternalBufferLease,
}
fn owned_reference(
    kind: &'static str,
    prefix: &'static str,
    id_hash: &[u8; 32],
    body_hash: &[u8; 32],
    session: &mut OriginalAuditSession,
) -> Result<WireRef> {
    let size = arithmetic(
        std::mem::size_of::<ExactRef>(),
        kind.len(),
        Op::Add,
        session,
    )?;
    let size = arithmetic(size, prefix.len(), Op::Add, session)?;
    let size = arithmetic(size, 64 + 71, Op::Add, session)?;
    let lease = session.reserve_external_payload(size).map_err(core_error)?;
    session
        .semantic_work()
        .write_bytes(2 * 71)
        .map_err(core_error)?;
    let id_digest = digest(id_hash);
    let body_digest = digest(body_hash);
    let id_length = arithmetic(prefix.len(), 64, Op::Add, session)?;
    session
        .semantic_work()
        .scan_bytes(2 * 71 + kind.len())
        .map_err(core_error)?;
    let mut id = String::new();
    id.try_reserve_exact(id_length)
        .map_err(|_| ServiceError::Unavailable)?;
    session
        .semantic_work()
        .write_bytes(prefix.len() + 64 + 71 + kind.len())
        .map_err(core_error)?;
    id.push_str(prefix);
    id.push_str(std::str::from_utf8(&id_digest[7..]).map_err(|_| ServiceError::IntegrityFailure)?);
    let body = std::str::from_utf8(&body_digest)
        .map_err(|_| ServiceError::IntegrityFailure)?
        .to_owned();
    Ok(WireRef {
        reference: ExactRef {
            kind: kind.to_owned(),
            id,
            digest: body,
        },
        _lease: lease,
    })
}

/// SAME JCS string encoder after admitting the transient Value/String copy.
/// Business text never goes through the ASCII-only literal emitter.
pub(super) fn string(text: &str, session: &mut OriginalAuditSession) -> Result<AuditedBytes> {
    let bytes = arithmetic(std::mem::size_of::<Value>(), text.len(), Op::Add, session)?;
    let _lease = session
        .reserve_external_payload(bytes)
        .map_err(core_error)?;
    session
        .semantic_work()
        .scan_bytes(text.len())
        .map_err(core_error)?;
    session
        .semantic_work()
        .write_bytes(text.len())
        .map_err(core_error)?;
    session.semantic_work().write_bytes(std::mem::size_of::<Value>()).map_err(core_error)?;
    let mut copy = String::new();
    copy.try_reserve_exact(text.len())
        .map_err(|_| ServiceError::Unavailable)?;
    copy.push_str(text);
    let value = Value::String(copy);
    session
        .canonical_representation(&value, RepresentationKind::SourceDefinition)
        .map_err(core_error)
}
pub(super) fn domain_digest(
    domain: &'static [u8],
    parts: &[&[u8]],
    session: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    let hashed = hash(domain, parts, session)?;
    session
        .semantic_work()
        .write_bytes(71)
        .map_err(core_error)?;
    let digest = digest(&hashed);
    literal(
        std::str::from_utf8(&digest).map_err(|_| ServiceError::IntegrityFailure)?,
        session,
    )
}
/// An owning canonical source record; still no origin or append capability.
pub(super) struct SourceRecord {
    schema: &'static str,
    storage: SourceRecordStorage,
}
enum SourceRecordStorage {
    Wire {
        body: AuditedBytes,
        reference: WireRef,
    },
    Initial {
        row: ledgerlab_core::policy::workflow::transition_constructor::InitialSourceRecord,
        _wrapper: ExternalBufferLease,
    },
}
impl SourceRecord {
    pub(super) fn schema(&self) -> &'static str {
        self.schema
    }
    pub(super) fn reference(&self) -> &ExactRef {
        match &self.storage {
            SourceRecordStorage::Wire { reference, .. } => &reference.reference,
            SourceRecordStorage::Initial { row, .. } => row.reference(),
        }
    }
    pub(super) fn bytes(&self) -> &[u8] {
        match &self.storage {
            SourceRecordStorage::Wire { body, .. } => body.bytes(),
            SourceRecordStorage::Initial { row, .. } => row.canonical_body(),
        }
    }
}
pub(super) fn initial_source_record(
    schema: &'static str,
    row: ledgerlab_core::policy::workflow::transition_constructor::InitialSourceRecord,
    session: &mut OriginalAuditSession,
) -> Result<SourceRecord> {
    // Retain the actual core row/Ref/body owner. No output byte or Ref copy,
    // second hash, Arc/triple cache or origin correspondence is introduced.
    let owner = session
        .reserve_external_payload(std::mem::size_of::<SourceRecord>())
        .map_err(core_error)?;
    session
        .semantic_work()
        .scan_bytes(std::mem::size_of_val(&row))
        .map_err(core_error)?;
    session
        .semantic_work()
        .write_bytes(std::mem::size_of::<SourceRecord>())
        .map_err(core_error)?;
    Ok(SourceRecord {
        schema,
        storage: SourceRecordStorage::Initial {
            row,
            _wrapper: owner,
        },
    })
}
pub(super) fn source_record(
    kind: &'static str,
    schema: &'static str,
    body: AuditedBytes,
    session: &mut OriginalAuditSession,
) -> Result<SourceRecord> {
    let schema_name = schema;
    let schema = literal(schema, session)?;
    let hashed = hash(
        b"bean-counter/workflow-document/1\0",
        &[b"[", schema.bytes(), b",", body.bytes(), b"]"],
        session,
    )?;
    let reference = owned_reference(kind, "wdoc_", &hashed, &hashed, session)?;
    Ok(SourceRecord {
        schema: schema_name,
        storage: SourceRecordStorage::Wire { body, reference },
    })
}

/// Exact existing SourceState identity, scoped to its original enrollment and
/// revision. This is representation DATA; it is not a source-head capability.
pub(super) fn source_state_record(
    body: AuditedBytes,
    store: &str,
    scope: &Value,
    enrollment_id: &str,
    revision: &str,
    session: &mut OriginalAuditSession,
) -> Result<SourceRecord> {
    let store = string(store, session)?;
    let scope = session
        .canonical_representation(scope, RepresentationKind::SourceDefinition)
        .map_err(core_error)?;
    let enrollment = string(enrollment_id, session)?;
    let revision = string(revision, session)?;
    let id = hash(
        b"bean-counter/workflow-source-state/1\0",
        &[
            b"[",
            store.bytes(),
            b",",
            scope.bytes(),
            b",",
            enrollment.bytes(),
            b",",
            revision.bytes(),
            b"]",
        ],
        session,
    )?;
    let digest = hash(
        b"bean-counter/workflow-record/1\0",
        &[
            b"[\"workflow-source-state\",",
            scope.bytes(),
            b",",
            body.bytes(),
            b"]",
        ],
        session,
    )?;
    let reference = owned_reference("workflow-source-state", "wsource_", &id, &digest, session)?;
    Ok(SourceRecord {
        schema: "ledger-workflow-source-state/1",
        storage: SourceRecordStorage::Wire { body, reference },
    })
}

/// Quote the SAME closed raw-request base64 result directly. Its encoded
/// text may exceed the256KiB RAW domain; it is not a SourceDefinition input.
pub(super) fn raw_request_base64(
    raw: &[u8],
    session: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    let encoded = session
        .encode_base64_representation(raw, RepresentationKind::OriginalRequest)
        .map_err(core_error)?;
    session
        .semantic_work()
        .scan_bytes(encoded.bytes().len())
        .map_err(core_error)?;
    literal(
        std::str::from_utf8(encoded.bytes()).map_err(|_| ServiceError::IntegrityFailure)?,
        session,
    )
}

/// Closed raw-request digest representation; no framed-domain relabeling.
pub(super) fn raw_request_digest(
    raw: &[u8],
    session: &mut OriginalAuditSession,
) -> Result<AuditedBytes> {
    let hash = session
        .hash_representation(raw, RepresentationKind::OriginalRequest)
        .map_err(core_error)?;
    session
        .semantic_work()
        .write_bytes(71)
        .map_err(core_error)?;
    let rendered = digest(&hash);
    literal(
        std::str::from_utf8(&rendered[7..]).map_err(|_| ServiceError::IntegrityFailure)?,
        session,
    )
}

